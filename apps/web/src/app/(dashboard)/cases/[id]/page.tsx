// ─── Checklist Tab ────────────────────────────────────────────────────────────

function ChecklistTab({
  caseId,
  user,
  isAdminOrClerk,
}: {
  caseId: string;
  user: ReturnType<typeof useAuth>["user"];
  isAdminOrClerk: boolean;
}) {
  const [items, setItems] = useState<CaseChecklistItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [initializing, setInitializing] = useState(false);
  const [showAddModal, setShowAddModal] = useState(false);
  const [addForm, setAddForm] = useState({ step: "", description: "" });
  const [saving, setSaving] = useState(false);

  function loadChecklist() {
    api
      .get<{ data: CaseChecklistItem[] }>(`/cases/${caseId}/checklist`)
      .then((res) => setItems(res.data))
      .catch(() => setItems([]))
      .finally(() => setLoading(false));
  }

  useEffect(() => { loadChecklist(); }, [caseId]);

  async function handleInitialize() {
    setInitializing(true);
    try {
      await api.post(`/cases/${caseId}/checklist/initialize`, {});
      loadChecklist();
    } catch {
      // ignore
    } finally {
      setInitializing(false);
    }
  }

  async function handleToggleComplete(item: CaseChecklistItem) {
    await api.patch(`/cases/${caseId}/checklist/${item.id}`, {
      isCompleted: !item.isCompleted,
    });
    loadChecklist();
  }

  async function handleAddStep() {
    setSaving(true);
    try {
      await api.post(`/cases/${caseId}/checklist`, {
        step: addForm.step,
        description: addForm.description || undefined,
      });
      setShowAddModal(false);
      setAddForm({ step: "", description: "" });
      loadChecklist();
    } catch {
      // ignore
    } finally {
      setSaving(false);
    }
  }

  if (loading) return <div className="text-sm text-gray-400">Loading checklist…</div>;

  const completed = items.filter((i) => i.isCompleted).length;
  const total = items.length;
  const progressPct = total === 0 ? 0 : Math.round((completed / total) * 100);

  return (
    <div>
      <div className="mb-4 flex items-center justify-between">
        <h2 className="text-lg font-semibold">Case Checklist</h2>
        {isAdminOrClerk && (
          <div className="flex gap-2">
            {items.length === 0 && (
              <button
                onClick={handleInitialize}
                disabled={initializing}
                className="rounded-lg bg-blue-700 px-3 py-1.5 text-sm font-medium text-white hover:bg-blue-800 disabled:opacity-50"
              >
                {initializing ? "Initializing…" : "Initialize Checklist"}
              </button>
            )}
            <button
              onClick={() => setShowAddModal(true)}
              className="rounded-lg border px-3 py-1.5 text-sm font-medium text-gray-600 hover:bg-gray-50"
            >
              Add Step
            </button>
          </div>
        )}
      </div>

      {items.length === 0 ? (
        <div className="rounded-lg border bg-white p-8 text-center text-sm text-gray-500">
          No checklist items. {isAdminOrClerk ? "Initialize the checklist or add custom steps." : "Contact staff to initialize the checklist."}
        </div>
      ) : (
        <>
          {/* Progress bar */}
          <div className="mb-6">
            <div className="mb-1 flex items-center justify-between text-sm">
              <span className="text-gray-600">{completed} of {total} steps completed</span>
              <span className="font-medium text-gray-900">{progressPct}%</span>
            </div>
            <div className="h-2 w-full overflow-hidden rounded-full bg-gray-200">
              <div
                className="h-full rounded-full bg-blue-600 transition-all"
                style={{ width: `${progressPct}%` }}
              />
            </div>
          </div>

          {/* Items */}
          <div className="space-y-2">
            {[...items].sort((a, b) => a.order - b.order).map((item) => (
              <div
                key={item.id}
                className={`flex items-start gap-3 rounded-lg border bg-white p-4 ${item.isCompleted ? "opacity-70" : ""}`}
              >
                <button
                  onClick={() => handleToggleComplete(item)}
                  className={`mt-0.5 flex h-5 w-5 shrink-0 items-center justify-center rounded border-2 transition ${
                    item.isCompleted
                      ? "border-green-500 bg-green-500 text-white"
                      : "border-gray-300 hover:border-blue-500"
                  }`}
                >
                  {item.isCompleted && <span className="text-xs">&#10003;</span>}
                </button>
                <div className="flex-1">
                  <p className={`font-medium text-sm ${item.isCompleted ? "line-through text-gray-400" : "text-gray-900"}`}>
                    {item.step}
                  </p>
                  {item.description && (
                    <p className="mt-0.5 text-xs text-gray-500">{item.description}</p>
                  )}
                  {item.isCompleted && item.completedAt && (
                    <p className="mt-0.5 text-xs text-gray-400">
                      Completed {formatDate(item.completedAt)}
                      {item.completedBy && ` by ${item.completedBy.firstName} ${item.completedBy.lastName}`}
                    </p>
                  )}
                </div>
              </div>
            ))}
          </div>
        </>
      )}

      {/* Add Step Modal */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/40 p-4">
          <div className="w-full max-w-md rounded-xl bg-white shadow-xl">
            <div className="flex items-center justify-between border-b px-6 py-4">
              <h2 className="text-lg font-semibold">Add Checklist Step</h2>
              <button onClick={() => setShowAddModal(false)} className="text-gray-400 hover:text-gray-600">✕</button>
            </div>
            <div className="space-y-4 p-6">
              <div>
                <label className="mb-1 block text-sm font-medium text-gray-700">Step Name *</label>
                <input
                  type="text"
                  value={addForm.step}
                  onChange={(e) => setAddForm({ ...addForm, step: e.target.value })}
                  className="w-full rounded-md border border-gray-300 px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500"
                />
              </div>
              <div>
                <label className="mb-1 block text-sm font-medium text-gray-700">Description</label>
                <textarea
                  value={addForm.description}
                  onChange={(e) => setAddForm({ ...addForm, description: e.target.value })}
                  rows={2}
                  className="w-full rounded-md border border-gray-300 px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500"
                />
              </div>
              <div className="flex justify-end gap-2 pt-2">
                <button
                  onClick={() => setShowAddModal(false)}
                  className="rounded-lg border px-4 py-2 text-sm font-medium text-gray-600 hover:bg-gray-50"
                >
                  Cancel
                </button>
                <button
                  onClick={handleAddStep}
                  disabled={saving || !addForm.step.trim()}
                  className="rounded-lg bg-blue-700 px-4 py-2 text-sm font-medium text-white hover:bg-blue-800 disabled:opacity-50"
                >
                  {saving ? "Saving…" : "Add Step"}
                </button>
              </div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}

