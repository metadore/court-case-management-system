// ─── Notifications Tab ────────────────────────────────────────────────────────

function NotificationsTab({
  id,
  subLoading,
  subscription,
  showSubForm,
  setShowSubForm,
  subChannels,
  subAll,
  subEvents,
  subPhone,
  subEmail,
  subSaving,
  subError,
  setSubscription,
  setSubSaving,
  setSubError,
}: {
  id: string;
  subLoading: boolean;
  subscription: NotificationSubscriptionItem | null | undefined;
  showSubForm: boolean;
  setShowSubForm: (v: boolean) => void;
  subChannels: string[];
  subAll: boolean;
  subEvents: string[];
  subPhone: string;
  subEmail: string;
  subSaving: boolean;
  subError: string | null;
  setSubscription: (v: NotificationSubscriptionItem | null) => void;
  setSubSaving: (v: boolean) => void;
  setSubError: (v: string | null) => void;
}) {
  return (
    <section>
      <div className="mb-3 flex items-center justify-between">
        <h2 className="text-lg font-semibold">Notifications</h2>
        {!subLoading && !subscription && !showSubForm && (
          <button
            onClick={() => setShowSubForm(true)}
            className="rounded-lg bg-blue-700 px-3 py-1.5 text-sm font-medium text-white hover:bg-blue-800"
          >
            Subscribe
          </button>
        )}
      </div>

      {subLoading ? (
        <p className="text-sm text-gray-400">Loading…</p>
      ) : subscription ? (
        <SubscriptionPanel
          sub={subscription}
          onCancel={async () => {
            await api.delete(`/subscriptions/${subscription.id}`);
            setSubscription(null);
            setShowSubForm(false);
          }}
          onEdit={() => setShowSubForm(true)}
        />
      ) : showSubForm ? (
        <SubscribeForm
          caseId={id}
          initial={{ channels: subChannels, subscribeAll: subAll, eventTypes: subEvents, email: subEmail, phone: subPhone }}
          saving={subSaving}
          error={subError}
          onCancel={() => setShowSubForm(false)}
          onSubmit={async (data) => {
            setSubSaving(true);
            setSubError(null);
            try {
              const res = await api.post<{ data: { subscription: NotificationSubscriptionItem; checkoutUrl?: string } }>(
                "/subscriptions", { caseId: id, ...data }
              );
              if (res.data.checkoutUrl) {
                window.location.href = res.data.checkoutUrl;
              } else {
                setSubscription(res.data.subscription);
                setShowSubForm(false);
              }
            } catch (err) {
              setSubError(err instanceof Error ? err.message : "Failed to subscribe.");
            } finally {
              setSubSaving(false);
            }
          }}
        />
      ) : (
        <Card className="p-6 text-center">
          <p className="text-sm text-gray-500">You are not subscribed to notifications for this case.</p>
          <button
            onClick={() => setShowSubForm(true)}
            className="mt-3 text-sm font-medium text-blue-600 hover:underline"
          >
            Subscribe to SMS / email updates &rarr;
          </button>
        </Card>
      )}
    </section>
  );
}

// ─── SubscriptionPanel ────────────────────────────────────────────────────────

function SubscriptionPanel({
  sub,
  onCancel,
  onEdit,
}: {
  sub: NotificationSubscriptionItem;
  onCancel: () => Promise<void>;
  onEdit: () => void;
}) {
  const [cancelling, setCancelling] = useState(false);

  async function handleCancel() {
    if (!confirm("Cancel notifications for this case?")) return;
    setCancelling(true);
    try { await onCancel(); } finally { setCancelling(false); }
  }

  return (
    <Card className="p-4">
      <div className="flex items-start justify-between">
        <div className="space-y-1 text-sm">
          <div className="flex items-center gap-2">
            <span className="font-medium text-gray-700">Channels:</span>
            {sub.channels.map((ch) => (
              <span key={ch} className="rounded-full bg-blue-100 px-2 py-0.5 text-xs font-medium text-blue-700">
                {ch}
              </span>
            ))}
          </div>
          <div>
            <span className="font-medium text-gray-700">Events: </span>
            <span className="text-gray-600">
              {sub.subscribeAll ? "All events" : `${sub.eventTypes.length} selected`}
            </span>
          </div>
          {sub.phone && <p className="text-gray-500">SMS &rarr; {sub.phone}</p>}
          {sub.email && <p className="text-gray-500">Email &rarr; {sub.email}</p>}
          {sub.activeUntil && (
            <p className="text-gray-400 text-xs">
              Active until {new Date(sub.activeUntil).toLocaleDateString()}
            </p>
          )}
        </div>
        <div className="flex gap-2">
          <button onClick={onEdit} className="rounded border px-3 py-1.5 text-xs font-medium text-gray-600 hover:bg-gray-50">
            Edit
          </button>
          <button
            onClick={handleCancel}
            disabled={cancelling}
            className="rounded border border-red-200 px-3 py-1.5 text-xs font-medium text-red-600 hover:bg-red-50 disabled:opacity-50"
          >
            {cancelling ? "Cancelling…" : "Cancel"}
          </button>
        </div>
      </div>
    </Card>
  );
}

// ─── SubscribeForm ────────────────────────────────────────────────────────────

function SubscribeForm({
  caseId: _caseId,
  initial,
  saving,
  error,
  onCancel,
  onSubmit,
}: {
  caseId: string;
  initial: { channels: string[]; subscribeAll: boolean; eventTypes: string[]; email: string; phone: string };
  saving: boolean;
  error: string | null;
  onCancel: () => void;
  onSubmit: (data: { channels: string[]; subscribeAll: boolean; eventTypes: string[]; email: string; phone: string }) => Promise<void>;
}) {
  const [channels, setChannels]     = useState<string[]>(initial.channels);
  const [subscribeAll, setSubAll]   = useState(initial.subscribeAll);
  const [eventTypes, setEventTypes] = useState<string[]>(initial.eventTypes);
  const [email, setEmail]           = useState(initial.email);
  const [phone, setPhone]           = useState(initial.phone);

  function toggleChannel(ch: string) {
    setChannels((prev) => prev.includes(ch) ? prev.filter((c) => c !== ch) : [...prev, ch]);
  }

  function toggleEvent(ev: string) {
    setEventTypes((prev) => prev.includes(ev) ? prev.filter((e) => e !== ev) : [...prev, ev]);
  }

  return (
    <Card className="p-6">
      <h3 className="mb-4 font-semibold text-gray-900">Subscribe to notifications</h3>

      {error && (
        <div className="mb-4 rounded border border-red-200 bg-red-50 p-3 text-sm text-red-700">{error}</div>
      )}

      <div className="space-y-5">
        <div>
          <p className="mb-2 text-sm font-medium text-gray-700">Channels</p>
          <div className="flex gap-4">
            {["SMS", "EMAIL"].map((ch) => (
              <label key={ch} className="flex cursor-pointer items-center gap-2 text-sm">
                <input
                  type="checkbox"
                  checked={channels.includes(ch)}
                  onChange={() => toggleChannel(ch)}
                  className="rounded"
                />
                {ch === "SMS" ? "SMS" : "Email"}
              </label>
            ))}
          </div>
        </div>

        {channels.includes("SMS") && (
          <div>
            <label className="mb-1 block text-sm font-medium text-gray-700">Phone number</label>
            <input
              type="tel"
              value={phone}
              onChange={(e) => setPhone(e.target.value)}
              placeholder="+1 555 000 0000"
              className="w-full rounded-md border border-gray-300 px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500"
            />
          </div>
        )}
        {channels.includes("EMAIL") && (
          <div>
            <label className="mb-1 block text-sm font-medium text-gray-700">Email address</label>
            <input
              type="email"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              placeholder="you@example.com"
              className="w-full rounded-md border border-gray-300 px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500"
            />
          </div>
        )}

        <div>
          <div className="mb-2 flex items-center justify-between">
            <p className="text-sm font-medium text-gray-700">Events</p>
            <label className="flex cursor-pointer items-center gap-2 text-sm text-gray-600">
              <input type="checkbox" checked={subscribeAll} onChange={(e) => setSubAll(e.target.checked)} className="rounded" />
              All events
            </label>
          </div>
          {!subscribeAll && (
            <div className="grid grid-cols-2 gap-2 rounded-lg border bg-gray-50 p-3">
              {ALL_EVENT_TYPES.map((ev) => (
                <label key={ev.value} className="flex cursor-pointer items-center gap-2 text-sm text-gray-700">
                  <input
                    type="checkbox"
                    checked={eventTypes.includes(ev.value)}
                    onChange={() => toggleEvent(ev.value)}
                    className="rounded"
                  />
                  {ev.label}
                </label>
              ))}
            </div>
          )}
        </div>
      </div>

      <div className="mt-5 flex justify-end gap-2">
        <button
          onClick={onCancel}
          className="rounded-lg border px-4 py-2 text-sm font-medium text-gray-600 hover:bg-gray-50"
        >
          Cancel
        </button>
        <button
          disabled={saving || channels.length === 0}
          onClick={() => onSubmit({ channels, subscribeAll, eventTypes, email, phone })}
          className="rounded-lg bg-blue-700 px-4 py-2 text-sm font-medium text-white hover:bg-blue-800 disabled:opacity-50"
        >
          {saving ? "Subscribing…" : "Subscribe"}
        </button>
      </div>
    </Card>
  );
}
