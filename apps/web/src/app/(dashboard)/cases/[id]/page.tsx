// ─── Local interfaces ────────────────────────────────────────────────────────

interface AuditEntry {
  id: string;
  action: string;
  entityType: string;
  entityId: string;
  fromState: string | null;
  toState: string | null;
  actorRole: string;
  actorUserId: string;
  createdAt: string;
}

interface CaseNote {
  id: string;
  caseId: string;
  authorId: string;
  content: string;
  visibility: "PRIVATE" | "JUDGES_AND_CLERKS" | "ALL_STAFF";
  isPinned: boolean;
  createdAt: string;
  updatedAt: string;
  author: { firstName: string; lastName: string };
}

interface Deadline {
  id: string;
  caseId: string;
  type: string;
  title: string;
  dueDate: string;
  completedAt: string | null;
  completedById: string | null;
  isAutoGenerated: boolean;
  notes: string | null;
  completedBy: { firstName: string; lastName: string } | null;
}

interface Motion {
  id: string;
  caseId: string;
  type: string;
  title: string;
  status: string;
  filedAt: string;
  respondByDate: string | null;
  replyByDate: string | null;
  decidedAt: string | null;
  notes: string | null;
  filedBy: { firstName: string; lastName: string };
  deadlines: Deadline[];
}

interface Evidence {
  id: string;
  caseId: string;
  title: string;
  description: string | null;
  type: string;
  status: string;
  custodianId: string | null;
  intakeDate: string;
  storageLocation: string | null;
  condition: string | null;
  exhibitNumber: string | null;
  custodian: { firstName: string; lastName: string } | null;
}

interface EvidenceTransfer {
  id: string;
  evidenceId: string;
  transferredAt: string;
  reason: string | null;
  fromCustodian: { firstName: string; lastName: string } | null;
  toCustodian: { firstName: string; lastName: string } | null;
}

interface CaseChecklistItem {
  id: string;
  step: string;
  description: string | null;
  order: number;
  isCompleted: boolean;
  completedAt: string | null;
  completedBy: { firstName: string; lastName: string } | null;
}

