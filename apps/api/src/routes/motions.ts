import type { FastifyInstance } from "fastify";
import { prisma } from "@tpt-court/database";
import { requireAuth } from "../middleware/requireAuth.js";
import { requireRole } from "../middleware/requireRole.js";
import { requireTenantScope } from "../middleware/tenantScope.js";
import { z } from "zod";
import { recordAuditLog } from "../lib/audit.js";

export default async function motionRoutes(app: FastifyInstance) {
  // ── List motions for a case ────────────────────────────────────────────
  app.get<{ Params: { caseId: string } }>(
    "/cases/:caseId/motions",
    { preHandler: [requireAuth, requireTenantScope] },
    async (request, reply) => {
      const { caseId } = request.params;

      const caseRecord = await prisma.case.findUnique({
        where: { id: caseId },
        select: { id: true, courtId: true },
      });
      if (!caseRecord) {
        return reply.status(404).send({ error: "NOT_FOUND", message: "Case not found", statusCode: 404 });
      }
      const userCourtId = request.user.courtId;
      if (userCourtId && caseRecord.courtId !== userCourtId) {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Access denied", statusCode: 403 });
      }

      const motions = await (prisma as any).motion.findMany({
        where: { caseId },
        include: {
          filedBy: { select: { id: true, firstName: true, lastName: true, role: true } },
          deadlines: {
            orderBy: { dueDate: "asc" },
          },
        },
        orderBy: { filedAt: "desc" },
      });

      return reply.send({ data: motions });
    },
  );

  // ── Create motion ──────────────────────────────────────────────────────
  app.post<{ Params: { caseId: string } }>(
    "/cases/:caseId/motions",
    { preHandler: [requireAuth, requireTenantScope, requireRole("ADMIN", "JUDGE", "CLERK", "LAWYER")] },
    async (request, reply) => {
      const { caseId } = request.params;

      const schema = z.object({
        type: z.enum([
          "MOTION_TO_DISMISS",
          "MOTION_FOR_SUMMARY_JUDGMENT",
          "MOTION_IN_LIMINE",
          "MOTION_TO_COMPEL",
          "MOTION_FOR_CONTINUANCE",
          "MOTION_FOR_DEFAULT_JUDGMENT",
          "MOTION_TO_SUPPRESS",
          "MOTION_FOR_RECONSIDERATION",
          "MOTION_FOR_SANCTIONS",
          "OTHER",
        ]),
        title: z.string().min(1).max(500),
        documentId: z.string().optional(),
        notes: z.string().max(5000).optional(),
        respondByDate: z.string().datetime().optional(),
        replyByDate: z.string().datetime().optional(),
      });

      const parsed = schema.safeParse(request.body);
      if (!parsed.success) {
        return reply.status(400).send({ error: "VALIDATION_ERROR", message: parsed.error.message, statusCode: 400 });
      }

      const caseRecord = await prisma.case.findUnique({
        where: { id: caseId },
        select: { id: true, courtId: true },
      });
      if (!caseRecord) {
        return reply.status(404).send({ error: "NOT_FOUND", message: "Case not found", statusCode: 404 });
      }
      const userCourtId = request.user.courtId;
      if (userCourtId && caseRecord.courtId !== userCourtId) {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Access denied", statusCode: 403 });
      }

      const motion = await (prisma as any).motion.create({
        data: {
          caseId,
          filedById: request.user.id,
          type: parsed.data.type,
          title: parsed.data.title,
          documentId: parsed.data.documentId ?? null,
          notes: parsed.data.notes ?? null,
          respondByDate: parsed.data.respondByDate ? new Date(parsed.data.respondByDate) : null,
          replyByDate: parsed.data.replyByDate ? new Date(parsed.data.replyByDate) : null,
        },
      });

      // Auto-create deadline records for respondByDate and replyByDate
      const deadlinesToCreate: Array<{
        caseId: string;
        motionId: string;
        type: string;
        title: string;
        dueDate: Date;
        isAutoGenerated: boolean;
      }> = [];

      if (parsed.data.respondByDate) {
        deadlinesToCreate.push({
          caseId,
          motionId: motion.id,
          type: "RESPONSE",
          title: `Response deadline — ${parsed.data.title}`,
          dueDate: new Date(parsed.data.respondByDate),
          isAutoGenerated: true,
        });
      }
      if (parsed.data.replyByDate) {
        deadlinesToCreate.push({
          caseId,
          motionId: motion.id,
          type: "REPLY",
          title: `Reply deadline — ${parsed.data.title}`,
          dueDate: new Date(parsed.data.replyByDate),
          isAutoGenerated: true,
        });
      }

      if (deadlinesToCreate.length > 0) {
        await (prisma as any).deadline.createMany({ data: deadlinesToCreate });
      }

      await recordAuditLog({
        prisma,
        actor: { id: request.user.id, role: request.user.role },
        courtId: caseRecord.courtId ?? null,
        entityType: "CASE",
        entityId: caseId,
        action: "MOTION_FILED",
        fromState: null,
        toState: "FILED",
        changes: { motionId: motion.id, type: motion.type, title: motion.title },
      });

      const fullMotion = await (prisma as any).motion.findUnique({
        where: { id: motion.id },
        include: {
          filedBy: { select: { id: true, firstName: true, lastName: true, role: true } },
          deadlines: { orderBy: { dueDate: "asc" } },
        },
      });

      return reply.status(201).send({ data: fullMotion });
    },
  );

  // ── Update motion ──────────────────────────────────────────────────────
  app.patch<{ Params: { caseId: string; id: string } }>(
    "/cases/:caseId/motions/:id",
    { preHandler: [requireAuth, requireTenantScope, requireRole("ADMIN", "JUDGE", "CLERK")] },
    async (request, reply) => {
      const { caseId, id } = request.params;

      const schema = z.object({
        status: z.enum([
          "FILED",
          "PENDING_RESPONSE",
          "RESPONSE_FILED",
          "UNDER_SUBMISSION",
          "GRANTED",
          "DENIED",
          "WITHDRAWN",
          "MOOT",
        ]).optional(),
        title: z.string().min(1).max(500).optional(),
        notes: z.string().max(5000).optional(),
        respondByDate: z.string().datetime().nullable().optional(),
        replyByDate: z.string().datetime().nullable().optional(),
        decidedAt: z.string().datetime().nullable().optional(),
      });

      const parsed = schema.safeParse(request.body);
      if (!parsed.success) {
        return reply.status(400).send({ error: "VALIDATION_ERROR", message: parsed.error.message, statusCode: 400 });
      }

      const existing = await (prisma as any).motion.findFirst({
        where: { id, caseId },
        include: { case: { select: { courtId: true } } },
      });
      if (!existing) {
        return reply.status(404).send({ error: "NOT_FOUND", message: "Motion not found", statusCode: 404 });
      }

      const userCourtId = request.user.courtId;
      if (userCourtId && existing.case.courtId !== userCourtId) {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Access denied", statusCode: 403 });
      }

      // Validate status transitions
      if (parsed.data.status && parsed.data.status !== existing.status) {
        const ALLOWED: Record<string, string[]> = {
          FILED: ["PENDING_RESPONSE"],
          PENDING_RESPONSE: ["RESPONSE_FILED"],
          RESPONSE_FILED: ["UNDER_SUBMISSION"],
          UNDER_SUBMISSION: ["GRANTED", "DENIED", "WITHDRAWN", "MOOT"],
          GRANTED: [],
          DENIED: [],
          WITHDRAWN: [],
          MOOT: [],
        };
        const allowed = ALLOWED[existing.status as string] ?? [];
        if (!allowed.includes(parsed.data.status)) {
          return reply.status(400).send({
            error: "INVALID_TRANSITION",
            message: `Cannot transition motion from ${existing.status} to ${parsed.data.status}. Allowed: ${allowed.join(", ") || "none"}.`,
            statusCode: 400,
          });
        }
      }

      const updateData: Record<string, unknown> = {};
      if (parsed.data.status !== undefined) updateData["status"] = parsed.data.status;
      if (parsed.data.title !== undefined) updateData["title"] = parsed.data.title;
      if (parsed.data.notes !== undefined) updateData["notes"] = parsed.data.notes;
      if (parsed.data.respondByDate !== undefined) {
        updateData["respondByDate"] = parsed.data.respondByDate ? new Date(parsed.data.respondByDate) : null;
      }
      if (parsed.data.replyByDate !== undefined) {
        updateData["replyByDate"] = parsed.data.replyByDate ? new Date(parsed.data.replyByDate) : null;
      }
      if (parsed.data.decidedAt !== undefined) {
        updateData["decidedAt"] = parsed.data.decidedAt ? new Date(parsed.data.decidedAt) : null;
      }

      const updated = await (prisma as any).motion.update({
        where: { id },
        data: updateData,
        include: {
          filedBy: { select: { id: true, firstName: true, lastName: true, role: true } },
          deadlines: { orderBy: { dueDate: "asc" } },
        },
      });

      if (parsed.data.status && parsed.data.status !== existing.status) {
        await recordAuditLog({
          prisma,
          actor: { id: request.user.id, role: request.user.role },
          courtId: existing.case.courtId ?? null,
          entityType: "CASE",
          entityId: caseId,
          action: "MOTION_STATUS_CHANGED",
          fromState: existing.status,
          toState: updated.status,
          changes: { motionId: id, status: { from: existing.status, to: updated.status } },
        });
      }

      return reply.send({ data: updated });
    },
  );

  // ── List deadlines for a case ──────────────────────────────────────────
  app.get<{ Params: { caseId: string } }>(
    "/cases/:caseId/deadlines",
    { preHandler: [requireAuth, requireTenantScope] },
    async (request, reply) => {
      const { caseId } = request.params;

      const caseRecord = await prisma.case.findUnique({
        where: { id: caseId },
        select: { id: true, courtId: true },
      });
      if (!caseRecord) {
        return reply.status(404).send({ error: "NOT_FOUND", message: "Case not found", statusCode: 404 });
      }
      const userCourtId = request.user.courtId;
      if (userCourtId && caseRecord.courtId !== userCourtId) {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Access denied", statusCode: 403 });
      }

      const deadlines = await (prisma as any).deadline.findMany({
        where: { caseId },
        include: {
          completedBy: { select: { id: true, firstName: true, lastName: true } },
          motion: { select: { id: true, title: true, type: true } },
        },
        orderBy: { dueDate: "asc" },
      });

      return reply.send({ data: deadlines });
    },
  );

  // ── Create standalone deadline ─────────────────────────────────────────
  app.post<{ Params: { caseId: string } }>(
    "/cases/:caseId/deadlines",
    { preHandler: [requireAuth, requireTenantScope, requireRole("ADMIN", "CLERK", "JUDGE")] },
    async (request, reply) => {
      const { caseId } = request.params;

      const schema = z.object({
        type: z.enum([
          "RESPONSE",
          "REPLY",
          "DISCOVERY_CUTOFF",
          "EXPERT_DISCLOSURE",
          "PRETRIAL_CONFERENCE",
          "TRIAL",
          "APPEAL",
          "SERVICE_OF_PROCESS",
          "OTHER",
        ]),
        title: z.string().min(1).max(500),
        dueDate: z.string().datetime(),
        motionId: z.string().optional(),
        notes: z.string().max(5000).optional(),
      });

      const parsed = schema.safeParse(request.body);
      if (!parsed.success) {
        return reply.status(400).send({ error: "VALIDATION_ERROR", message: parsed.error.message, statusCode: 400 });
      }

      const caseRecord = await prisma.case.findUnique({
        where: { id: caseId },
        select: { id: true, courtId: true },
      });
      if (!caseRecord) {
        return reply.status(404).send({ error: "NOT_FOUND", message: "Case not found", statusCode: 404 });
      }
      const userCourtId = request.user.courtId;
      if (userCourtId && caseRecord.courtId !== userCourtId) {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Access denied", statusCode: 403 });
      }

      const deadline = await (prisma as any).deadline.create({
        data: {
          caseId,
          type: parsed.data.type,
          title: parsed.data.title,
          dueDate: new Date(parsed.data.dueDate),
          motionId: parsed.data.motionId ?? null,
          notes: parsed.data.notes ?? null,
          isAutoGenerated: false,
        },
        include: {
          completedBy: { select: { id: true, firstName: true, lastName: true } },
          motion: { select: { id: true, title: true, type: true } },
        },
      });

      await recordAuditLog({
        prisma,
        actor: { id: request.user.id, role: request.user.role },
        courtId: caseRecord.courtId ?? null,
        entityType: "CASE",
        entityId: caseId,
        action: "DEADLINE_CREATED",
        fromState: null,
        toState: null,
        changes: { deadlineId: deadline.id, type: deadline.type, dueDate: deadline.dueDate },
      });

      return reply.status(201).send({ data: deadline });
    },
  );

  // ── Mark deadline complete ─────────────────────────────────────────────
  app.patch<{ Params: { caseId: string; id: string } }>(
    "/cases/:caseId/deadlines/:id",
    { preHandler: [requireAuth, requireTenantScope] },
    async (request, reply) => {
      const { caseId, id } = request.params;

      // Any staff (not PUBLIC) can mark deadlines complete
      if (request.user.role === "PUBLIC") {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Insufficient permissions", statusCode: 403 });
      }

      const schema = z.object({
        isCompleted: z.boolean(),
      });

      const parsed = schema.safeParse(request.body);
      if (!parsed.success) {
        return reply.status(400).send({ error: "VALIDATION_ERROR", message: parsed.error.message, statusCode: 400 });
      }

      const existing = await (prisma as any).deadline.findFirst({
        where: { id, caseId },
        include: { case: { select: { courtId: true } } },
      });
      if (!existing) {
        return reply.status(404).send({ error: "NOT_FOUND", message: "Deadline not found", statusCode: 404 });
      }

      const userCourtId = request.user.courtId;
      if (userCourtId && existing.case.courtId !== userCourtId) {
        return reply.status(403).send({ error: "FORBIDDEN", message: "Access denied", statusCode: 403 });
      }

      const updated = await (prisma as any).deadline.update({
        where: { id },
        data: {
          isCompleted: parsed.data.isCompleted,
          completedAt: parsed.data.isCompleted ? new Date() : null,
          completedById: parsed.data.isCompleted ? request.user.id : null,
        },
        include: {
          completedBy: { select: { id: true, firstName: true, lastName: true } },
          motion: { select: { id: true, title: true, type: true } },
        },
      });

      return reply.send({ data: updated });
    },
  );
}
